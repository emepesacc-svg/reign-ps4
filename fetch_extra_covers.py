#!/usr/bin/env python3
"""REIGN — fetch real covers for the extra games (ids 158+) from the public Steam Store.
Run from the project root on YOUR computer (needs internet):  python fetch_extra_covers.py
It looks each title up on Steam, downloads the cover + header into assets/covers/ and writes
reign-covers.js, which the site loads automatically. Titles that are not on Steam (e.g. PlayStation
exclusives) keep the generated cover. Re-running is safe: files already downloaded are skipped.
Check the results visually; a match by name can occasionally pick the wrong edition.
"""
import difflib, json, re, sys, time, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'assets' / 'covers'
UA = 'REIGN-ULTRA-Cover-Fetcher/1.0 (personal static-site asset downloader)'
CDN = 'https://shared.akamai.steamstatic.com/store_item_assets/steam/apps/{}/{}'


def get(url, timeout=25):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def norm(t):
    return re.sub(r'[^a-z0-9]+', ' ', t.lower().replace('’', "'")).strip()


def find_app(title):
    q = urllib.parse.quote(title)
    data = json.loads(get(f'https://store.steampowered.com/api/storesearch/?term={q}&l=english&cc=us'))
    best, score = None, 0.0
    for it in data.get('items', []):
        s = difflib.SequenceMatcher(None, norm(title), norm(it.get('name', ''))).ratio()
        if s > score:
            best, score = it, s
    return (best['id'], best['name'], score) if best and score >= 0.88 else None


def save(url, path):
    try:
        d = get(url)
    except Exception:
        return False
    if len(d) < 1500 or not (d.startswith(b'\xff\xd8\xff') or d.startswith(b'\x89PNG')):
        return False
    path.write_bytes(d)
    return True


def main():
    src = (ROOT / 'reign-games-extra.js').read_text(encoding='utf-8')
    rows = json.loads(re.search(r'var ROWS=(\[.*?\]);\n', src, re.S).group(1))
    OUT.mkdir(parents=True, exist_ok=True)
    covers, start = {}, 158
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else len(rows)
    for i, r in enumerate(rows[:limit]):
        gid, title = start + i, r[0]
        img, hdr = OUT / f'{gid}.jpg', OUT / f'{gid}-h.jpg'
        if img.exists() and hdr.exists():
            covers[gid] = {'image': f'assets/covers/{gid}.jpg', 'header': f'assets/covers/{gid}-h.jpg'}
            continue
        try:
            hit = find_app(title)
        except Exception as e:
            print('!', title, e); time.sleep(1.5); continue
        if not hit:
            print('-', title, '(no confident Steam match)'); time.sleep(.4); continue
        app, name, sc = hit
        ok1 = save(CDN.format(app, 'library_600x900.jpg'), img)
        ok2 = save(CDN.format(app, 'header.jpg'), hdr)
        if ok1 or ok2:
            covers[gid] = {'image': f'assets/covers/{gid}.jpg' if ok1 else f'assets/covers/{gid}-h.jpg',
                           'header': f'assets/covers/{gid}-h.jpg' if ok2 else f'assets/covers/{gid}.jpg'}
            print('+', title, '->', name, f'({sc:.2f})')
        else:
            print('-', title, '(images unavailable)')
        time.sleep(.6)
    (ROOT / 'reign-covers.js').write_text('/* Generated by fetch_extra_covers.py */\nwindow.REIGN_COVERS = ' + json.dumps(covers, indent=1) + ';\n', encoding='utf-8')
    print(f'Done: {len(covers)} covers. Reload the site (Ctrl+F5).')


if __name__ == '__main__':
    main()
